export function getLanguage() {
  const raw = new URLSearchParams(window.location.search).get("lang") || "";
  const normalized = raw.trim().toLowerCase().slice(0, 2);
  return SUPPORTED_LANGS.has(normalized) ? normalized : "zh";
}

export function getExcalidrawLanguage(lang) {
  if (lang === "ja") return "ja-JP";
  if (lang === "en") return "en";
  return "zh-CN";
}

export function getHtmlLanguage(lang) {
  if (lang === "ja") return "ja";
  if (lang === "en") return "en";
  return "zh-CN";
}

export function translate(lang, key, variables = {}) {
  const template = COPY[lang]?.[key] || COPY.zh[key] || key;
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
}

export function languageHref(lang) {
  const url = new URL(window.location.href);
  url.searchParams.set("lang", lang);
  url.hash = "";
  return `${url.pathname}${url.search}`;
}
