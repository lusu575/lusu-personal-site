import { readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const committedUrl = new URL("worker-configuration.d.ts", root);
const rootPath = fileURLToPath(root);
const generatedPath = join(
  rootPath,
  `.worker-configuration.${process.pid}.${Date.now()}.d.ts`
);
const wranglerPath = fileURLToPath(new URL(
  process.platform === "win32" ? "node_modules/.bin/wrangler.cmd" : "node_modules/.bin/wrangler",
  root
));

function normalizeGeneratedTypes(value) {
  return value
    .replace(
      /^\/\/ Generated by Wrangler by running `wrangler types(?: [^`]*)?` \(hash:/mu,
      "// Generated by Wrangler by running `wrangler types` (hash:"
    )
    .replace(/[ \t]+$/gm, "")
    .replace(/\n+$/u, "\n");
}

try {
  const result = spawnSync(wranglerPath, ["types", generatedPath], {
    cwd: rootPath,
    encoding: "utf8",
    stdio: "inherit"
  });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);

  const [committed, generated] = await Promise.all([
    readFile(committedUrl, "utf8"),
    readFile(generatedPath, "utf8")
  ]);
  if (normalizeGeneratedTypes(committed) !== normalizeGeneratedTypes(generated)) {
    console.error("worker-configuration.d.ts is stale; run `wrangler types` and normalize trailing whitespace.");
    process.exitCode = 1;
  }
} finally {
  await rm(generatedPath, { force: true });
}
