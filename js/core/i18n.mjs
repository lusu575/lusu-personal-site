export const supportedLanguages = Object.freeze(["zh", "en", "ja"]);

export function normalizeLanguage(value) {
  const language = String(value || "").trim().toLowerCase().split("-")[0];
  return supportedLanguages.includes(language) ? language : "zh";
}

export function translationFor(key, language, fallbackLanguage = "zh") {
  const normalizedKey = typeof key === "string" ? key.trim() : "";
  if (!normalizedKey) return "";
  const primary = translations[normalizeLanguage(language)]?.[normalizedKey];
  if (typeof primary === "string") return primary;
  const fallback = translations[normalizeLanguage(fallbackLanguage)]?.[normalizedKey];
  return typeof fallback === "string" ? fallback : "";
}

export function translationKeyDiff(catalog = translations, referenceLanguage = "zh") {
  const reference = normalizeLanguage(referenceLanguage);
  const expected = new Set(Object.keys(catalog?.[reference] || {}));
  return Object.freeze(Object.fromEntries(supportedLanguages.map((language) => {
    const actual = new Set(Object.keys(catalog?.[language] || {}));
    return [language, Object.freeze({
      missing: Object.freeze([...expected].filter((key) => !actual.has(key)).sort()),
      extra: Object.freeze([...actual].filter((key) => !expected.has(key)).sort())
    })];
  })));
}

export function isI18nNodeInScope(node, activePage) {
  const owningPage = node?.closest?.(".page") || null;
  return !owningPage || owningPage === activePage;
}

